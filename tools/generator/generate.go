package main

import (
	"fmt"
	"strings"
)

// modelGroupPrefixPrefix Model 文件分组前缀段数
const modelGroupSegments = 2

// generateModels 生成 model/ 包：按 schema 名前两段分文件
func (g *genContext) generateModels() error {
	if err := ensureDir(g.outDir + "/model"); err != nil {
		return err
	}

	// 分组：schema 名前 N 段（大写字母作为分隔）→ 文件名
	groups := make(map[string][]modelInfo)
	var groupOrder []string
	for _, m := range g.models {
		key := modelGroupKey(m.Name)
		if _, exists := groups[key]; !exists {
			groupOrder = append(groupOrder, key)
		}
		groups[key] = append(groups[key], m)
	}

	for _, key := range groupOrder {
		var sb strings.Builder
		writeModelHeader(&sb, g.genTime)
		for _, m := range groups[key] {
			writeModelStruct(&sb, m)
		}
		path := fmt.Sprintf("%s/model/%s.go", g.outDir, safeFileName(key))
		if err := writeFile(path, sb.String()); err != nil {
			return err
		}
	}
	return nil
}

// safeFileName 将分组键转为文件名；以 _test 结尾的键会被 Go 工具链视为测试文件，
// 导致 go build 不编译该文件，此处追加 _schema 后缀规避。
func safeFileName(key string) string {
	if strings.HasSuffix(key, "_test") {
		return key + "_schema"
	}
	return key
}

// modelGroupKey 按 PascalCase 拆分取前 2 段作为文件分组键（snake_file 名）
func modelGroupKey(name string) string {
	segs := splitPascal(name)
	n := modelGroupSegments
	if len(segs) < n {
		n = len(segs)
	}
	parts := make([]string, n)
	for i := 0; i < n; i++ {
		parts[i] = strings.ToLower(segs[i])
	}
	return strings.Join(parts, "_")
}

// splitPascal 按 PascalCase 大写字母切分（连续大写视为一段词首）
func splitPascal(s string) []string {
	var segs []string
	var cur strings.Builder
	runes := []rune(s)
	for i, r := range runes {
		if r >= 'A' && r <= 'Z' {
			// 前一字符非大写 → 新段起点；连续大写遇到小写时也断（如 "OpenAPIModel" → Open API Model）
			if cur.Len() > 0 {
				prevIsUpper := i > 0 && runes[i-1] >= 'A' && runes[i-1] <= 'Z'
				nextIsLower := i+1 < len(runes) && runes[i+1] >= 'a' && runes[i+1] <= 'z'
				if !prevIsUpper || nextIsLower {
					segs = append(segs, cur.String())
					cur.Reset()
				}
			}
		}
		cur.WriteRune(r)
	}
	if cur.Len() > 0 {
		segs = append(segs, cur.String())
	}
	return segs
}

// writeModelHeader 写 model 文件头
func writeModelHeader(sb *strings.Builder, genTime string) {
	sb.WriteString("// Code generated by tools/generator from oasSchema.json. DO NOT EDIT.\n")
	sb.WriteString("// 生成时间: " + genTime + "\n\n")
	sb.WriteString("package model\n\n")
}

// writeModelStruct 写单个 struct
func writeModelStruct(sb *strings.Builder, m modelInfo) {
	if m.Description != "" {
		writeComment(sb, m.Name+" "+m.Description)
	} else {
		fmt.Fprintf(sb, "// %s 对应 oasSchema 中的同名 schema。\n", m.Name)
	}
	fmt.Fprintf(sb, "type %s struct {\n", m.Name)
	if len(m.Fields) == 0 {
		sb.WriteString("\t_ struct{} // 空对象\n")
	}
	for _, f := range m.Fields {
		if f.Comment != "" {
			writeComment(sb, f.GoName+" "+f.Comment)
		}
		if f.Required {
			fmt.Fprintf(sb, "\t%s %s `json:\"%s\"`\n", f.GoName, f.GoType, f.JSONName)
		} else {
			fmt.Fprintf(sb, "\t%s %s `json:\"%s,omitempty\"`\n", f.GoName, f.GoType, f.JSONName)
		}
	}
	sb.WriteString("}\n\n")
}

// writeComment 写注释块（自动断行）
func writeComment(sb *strings.Builder, text string) {
	const maxLen = 100
	lineLen := 0
	fmt.Fprint(sb, "//")
	for _, word := range strings.Fields(text) {
		if lineLen+len(word)+1 > maxLen {
			fmt.Fprint(sb, "\n//")
			lineLen = 0
		}
		fmt.Fprintf(sb, " %s", word)
		lineLen += len(word) + 1
	}
	fmt.Fprint(sb, "\n")
}

// generateAPIs 生成 api/ 包：按 tag 一文件
func (g *genContext) generateAPIs() error {
	if err := ensureDir(g.outDir + "/api"); err != nil {
		return err
	}

	for _, tag := range g.tags {
		className := g.operations[g.tagOps[tag][0]].ClassName
		var sb strings.Builder
		sb.WriteString("// Code generated by tools/generator from oasSchema.json. DO NOT EDIT.\n")
		sb.WriteString("// 生成时间: " + g.genTime + "\n\n")
		sb.WriteString("package api\n\n")
		sb.WriteString("import (\n")
		sb.WriteString("\t\"github.com/jcbowen/alipay-sdk-go-all\"\n")
		sb.WriteString("\t\"github.com/jcbowen/alipay-sdk-go-all/model\"\n")
		// 该 tag 下存在查询参数的方法会使用 fmt.Sprint
		hasQuery := false
		for _, idx := range g.tagOps[tag] {
			if len(g.operations[idx].QueryParams) > 0 {
				hasQuery = true
				break
			}
		}
		if hasQuery {
			sb.WriteString("\t\"fmt\"\n")
		}
		sb.WriteString(")\n\n")

		writeComment(&sb, className+" "+tag+" 相关接口（由 operationId tag 归组）")
		fmt.Fprintf(&sb, "type %s struct {\n\texecutor *alipay.GenericExecuteApi\n}\n\n", className)

		fmt.Fprintf(&sb, "// New%s 创建 API 实例。\n", className)
		writeComment(&sb, "参数:\nconfigUtil: 配置工具（由 alipay.NewAlipayConfigUtil 构建）")
		fmt.Fprintf(&sb, "func New%s(configUtil *alipay.AlipayConfigUtil) (*%s, error) {\n", className, className)
		fmt.Fprintf(&sb, "\texecutor, err := alipay.NewGenericExecuteApi(configUtil)\n")
		sb.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		fmt.Fprintf(&sb, "\treturn &%s{executor: executor}, nil\n}\n\n", className)

		fmt.Fprintf(&sb, "// New%sWithExecutor 复用已有执行器创建（可与其它 API 共享 HTTP 客户端与 baseUrl 配置）。\n", className)
		fmt.Fprintf(&sb, "func New%sWithExecutor(executor *alipay.GenericExecuteApi) *%s {\n", className, className)
		fmt.Fprintf(&sb, "\treturn &%s{executor: executor}\n}\n\n", className)

		for _, idx := range g.tagOps[tag] {
			if err := g.writeOperation(&sb, g.operations[idx]); err != nil {
				return err
			}
		}

		path := fmt.Sprintf("%s/api/%s.go", g.outDir, safeFileName(strings.ReplaceAll(tag, ".", "_")))
		if err := writeFile(path, sb.String()); err != nil {
			return err
		}
	}
	return nil
}

// writeOperation 写单个 API 方法
func (g *genContext) writeOperation(sb *strings.Builder, op operationInfo) error {
	// 签名注释
	fmt.Fprintf(sb, "// %s %s\n", op.MethodName, op.Summary)
	writeComment(sb, "HTTP "+op.HTTPMethod+" "+op.Path)

	// 参数列表
	var params []string
	if op.RequestModel != "" {
	 paramName := lowerFirstCamel(op.RequestModel)
	 params = append(params, fmt.Sprintf("%s *model.%s", paramName, op.RequestModel))
	}
	for _, f := range op.FileFields {
		params = append(params, fmt.Sprintf("%s *alipay.UploadFile", f.GoName))
	}
	for _, qp := range op.QueryParams {
		params = append(params, fmt.Sprintf("%s %s", qp.GoName, qp.GoType))
	}
	if len(params) > 0 {
		for _, p := range params {
			writeComment(sb, "- "+p)
		}
	}
	writeComment(sb, "- cp *alipay.CustomizedParams 可选，用于 appAuthToken 与自定义参数")
	writeComment(sb, "返回值:")
	if op.ResponseModel != "" {
		writeComment(sb, fmt.Sprintf("- *model.%s 响应对象", op.ResponseModel))
	} else {
		writeComment(sb, "- 无响应体（nil）")
	}
	writeComment(sb, "- *alipay.ApiException 异常（nil 表示成功）")

	fmt.Fprintf(sb, "func (a *%s) %s(", op.ClassName, op.MethodName)
	if len(params) == 0 {
		fmt.Fprintf(sb, "cp *alipay.CustomizedParams) ")
	} else {
		sb.WriteString("\n")
		for _, p := range params {
			fmt.Fprintf(sb, "\t%s,\n", p)
		}
		sb.WriteString("\tcp *alipay.CustomizedParams) ")
	}
	if op.ResponseModel != "" {
		fmt.Fprintf(sb, "(*model.%s, *alipay.ApiException) {\n", op.ResponseModel)
	} else {
		sb.WriteString("*alipay.ApiException {\n")
	}

	// 请求构造
	if len(op.FileFields) > 0 {
		fmt.Fprintf(sb, "\treq := &alipay.OpenApiGenericRequest{\n")
		sb.WriteString("\t\tFileParams: map[string][]*alipay.UploadFile{\n")
		for _, f := range op.FileFields {
			fmt.Fprintf(sb, "\t\t\t\"%s\": {%s},\n", f.Name, f.GoName)
		}
		sb.WriteString("\t\t},\n\t}\n")
	} else if op.RequestModel != "" {
		paramName := lowerFirstCamel(op.RequestModel)
		fmt.Fprintf(sb, "\treq := &alipay.OpenApiGenericRequest{BodyParams: %s}\n", paramName)
	} else {
		sb.WriteString("\treq := &alipay.OpenApiGenericRequest{}\n")
	}

	// 查询参数
	for _, qp := range op.QueryParams {
		fmt.Fprintf(sb, "\tif %s != nil {\n", qp.GoName)
		fmt.Fprintf(sb, "\t\treq.AddQueryParam(\"%s\", fmt.Sprint(*%s))\n", qp.Name, qp.GoName)
		sb.WriteString("\t}\n")
	}

	// cp 扩展参数合并
	sb.WriteString("\tif cp != nil {\n")
	sb.WriteString("\t\treq.ApplyCustomizedParams(cp)\n")
	sb.WriteString("\t}\n")

	// 执行
	if op.ResponseModel != "" {
		fmt.Fprintf(sb, "\tresult := &model.%s{}\n", op.ResponseModel)
		fmt.Fprintf(sb, "\tif apiErr := a.executor.ExecuteWithResult(\"%s\", \"%s\", req, result); apiErr != nil {\n", op.Path, op.HTTPMethod)
		sb.WriteString("\t\treturn nil, apiErr\n\t}\n")
		sb.WriteString("\treturn result, nil\n}\n\n")
	} else {
		fmt.Fprintf(sb, "\treturn a.executor.ExecuteWithResult(\"%s\", \"%s\", req, nil)\n}\n\n", op.Path, op.HTTPMethod)
	}
	return nil
}

// generateEndpointDoc 生成 docs/endpoints.md 全量端点表
func (g *genContext) generateEndpointDoc() error {
	if err := ensureDir(g.outDir + "/docs"); err != nil {
		return err
	}

	var sb strings.Builder
	sb.WriteString("# 支付宝开放平台 V3 API 端点全表\n\n")
	sb.WriteString("> 由 tools/generator 从 oasSchema.json 生成，与 api/ 包代码保持同步。\n\n")
	sb.WriteString("| API 类 | 方法 | HTTP | 路径 | 请求 Model | 响应 Model |\n")
	sb.WriteString("|---|---|---|---|---|---|\n")

	for _, tag := range g.tags {
		for _, idx := range g.tagOps[tag] {
			op := g.operations[idx]
			reqModel := "-"
			if op.RequestModel != "" {
				reqModel = op.RequestModel
			} else if len(op.FileFields) > 0 {
				names := make([]string, 0, len(op.FileFields))
				for _, f := range op.FileFields {
					names = append(names, f.Name)
				}
				reqModel = "multipart(" + strings.Join(names, ", ") + ")"
			}
			respModel := "-"
			if op.ResponseModel != "" {
				respModel = op.ResponseModel
			}
			fmt.Fprintf(&sb, "| %s | %s | %s | `%s` | %s | %s |\n",
				op.ClassName, op.MethodName, op.HTTPMethod, op.Path, reqModel, respModel)
		}
	}

	return writeFile(g.outDir+"/docs/endpoints.md", sb.String())
}
